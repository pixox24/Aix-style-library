def features(*rows):
    return [{"id": "F%02d" % (i + 1), "axis": a, "tier": t, "text": x}
            for i, (a, t, x) in enumerate(rows)]


def avoid(*texts):
    return [{"id": "N%02d" % (i + 1), "text": x} for i, x in enumerate(texts)]


def style(id, name, category, description, tags, aliases, alt, feature_rows,
          avoid_rows, suitable, weak, failure, plan):
    return dict(id=id, name=name, category=category, description=description,
                tags=tags, aliases=aliases, alt=alt,
                features=features(*feature_rows), avoid=avoid(*avoid_rows),
                suitable_for=suitable, weak_for=weak,
                known_failures=[failure], plan=plan)


